insert into public.monitor_checks (monitor_id, checked_at, latency_ms, status_code, ok)
select
  m.id,
  now() - (point * interval '5 minutes'),
  greatest(35, round(70 + m.id * 23 + random() * 48 + sin(point / 17.0) * 22))::integer,
  case when m.name = '数据 API' and point between 78 and 83 then 503 else 200 end,
  not (m.name = '数据 API' and point between 78 and 83)
from public.monitors m
cross join generate_series(0, 287) as point
where not exists (select 1 from public.monitor_checks limit 1);

